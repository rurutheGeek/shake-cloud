MEDIA_KEY = b'gfxEiUp1d43vwJQm'  # 固定鍵（実測。.env 等にある場合は差し替え）


def _state(key: bytes) -> list[int]:
    st = [0, 0, 0, 0]
    for b in key:
        st[0] = (st[0] + b) & 0xFF
        st[1] = (st[1] - b) & 0xFF
        st[3] = (st[3] ^ b) & 0xFF
    return st


def _crypt(data: bytes, key: bytes) -> bytes:
    st = _state(key)
    out = bytearray()
    prev = 0
    for i, b in enumerate(data):
        x = prev if i > 0 else 0
        out.append(TABLE[(x + st[x & 3]) & 0xFF] ^ b)
        prev = b if i == 0 else data[i]  # feedback = previous ciphertext byte
    return bytes(out)


def decrypt(data: bytes, key: bytes = MEDIA_KEY) -> bytes:
    """復号（暗号化と同一式。自己同期ストリーム暗号）。"""
    st = _state(key)
    out = bytearray()
    prev = 0
    for i, b in enumerate(data):
        x = prev if i > 0 else 0
        out.append(TABLE[(x + st[x & 3]) & 0xFF] ^ b)
        prev = b  # previous ciphertext
    return bytes(out)


def encrypt(plain: bytes, key: bytes = MEDIA_KEY) -> bytes:
    st = _state(key)
    out = bytearray()
    prev = 0
    for i, b in enumerate(plain):
        x = prev if i > 0 else 0
        c = TABLE[(x + st[x & 3]) & 0xFF] ^ b
        out.append(c)
        prev = c  # previous ciphertext
    return bytes(out)
